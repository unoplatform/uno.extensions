using System;
using System.Collections.Generic;
using System.Linq;
using Microsoft.CodeAnalysis;
using Uno.Extensions.Generators;

namespace Uno.Extensions.Reactive.Generator;

/// <summary>
/// The public <c>HasErrors</c> property of a generated view model, which exposes its validation state (cf. INotifyDataErrorInfo) to bindings.
/// </summary>
/// <remarks>
/// BindableViewModelBase implements only the INotifyDataErrorInfo.HasErrors explicitly: a public HasErrors on the base class would conflict with
/// a HasErrors already declared by the user in its partial view model (CS0108, an error with TreatWarningsAsErrors).
/// So the property is generated for each view model (by all versions of the generation tool), unless that name is already used.
/// </remarks>
internal static class ValidationStateMember
{
	/// <summary>
	/// Gets the code of the HasErrors property of a view model, or an empty string if that name is already used (reported using FEED1001).
	/// </summary>
	/// <param name="ctx">The generation context.</param>
	/// <param name="model">The model for which the view model is generated.</param>
	/// <param name="vmName">The name of the generated view model.</param>
	/// <param name="hasBaseViewModel">Indicates if the view model inherits from another generated view model (which already declares the property).</param>
	/// <param name="generatedMemberNames">The names of the members generated in the view model (e.g. mapped from the model).</param>
	public static string Generate(BindableGenerationContext ctx, INamedTypeSymbol model, string vmName, bool hasBaseViewModel, IEnumerable<string> generatedMemberNames)
	{
		var hidingMember = generatedMemberNames.Contains(N.HasErrors, StringComparer.Ordinal)
			? FindHasErrors(model) ?? (ISymbol)model
			: FindUserViewModel(model, vmName) is { } userViewModel
				? FindHasErrors(userViewModel)
				: null;

		if (hidingMember is not null)
		{
			ctx.Context.ReportDiagnostic(Rules.FEED1001.GetDiagnostic(hidingMember.ContainingType ?? model, hidingMember, vmName));
			return string.Empty;
		}

		if (hasBaseViewModel)
		{
			return string.Empty;
		}

		return $@"
			/// <summary>
			/// Indicates if any of the properties of this view model has validation errors (cf. <see cref=""global::System.ComponentModel.INotifyDataErrorInfo""/>).
			/// </summary>
			public bool {N.HasErrors} => ((global::System.ComponentModel.INotifyDataErrorInfo)this).HasErrors;";
	}

	private static ISymbol? FindHasErrors(INamedTypeSymbol type)
		=> type.GetMembers(N.HasErrors).FirstOrDefault(member => !member.IsStatic && !member.IsImplicitlyDeclared);

	// The partial view model declared by the user, if any (the members generated by this generator are not visible here).
	private static INamedTypeSymbol? FindUserViewModel(INamedTypeSymbol model, string vmName)
		=> model.GetTypeMembers(vmName) // Nested in the model (generation tool v1)
			.Concat(model.ContainingType?.GetTypeMembers(vmName) ?? model.ContainingNamespace.GetTypeMembers(vmName))
			.FirstOrDefault(type => type.Arity is 0);
}
