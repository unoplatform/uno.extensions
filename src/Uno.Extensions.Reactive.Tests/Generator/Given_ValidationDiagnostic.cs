extern alias ReactiveGenerator;

using System;
using System.IO;
using System.Linq;
using FluentAssertions;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.VisualStudio.TestTools.UnitTesting;
using FeedsGenerator = ReactiveGenerator::Uno.Extensions.Reactive.Generator.FeedsGenerator;

namespace Uno.Extensions.Reactive.Tests.Generator;

[TestClass]
public class Given_ValidationDiagnostic
{
	private const string Header = """
		using System;
		using Uno.Extensions.Reactive;

		[assembly: Uno.Extensions.Reactive.Config.BindableGenerationTool(3)]

		namespace App;
		""";

	[TestMethod]
	public void When_ModelDeclaresHasErrors_Then_Diagnostic()
	{
		var (diagnostics, compilation) = Run(Header + """

			public partial class MyModel
			{
				public IState<string> Name => State.Value(this, () => "");

				public IFeed<bool> HasErrors => Feed.Async(async ct => false);
			}
			""");

		diagnostics.Should().ContainSingle(d => d.Id == "FEED1001")
			.Which.GetMessage().Should().Contain("HasErrors").And.Contain("MyModel");
		compilation.GetDiagnostics().Where(d => d.Severity == DiagnosticSeverity.Error).Should().BeEmpty();
	}

	[TestMethod]
	public void When_RecordDeclaresHasErrors_Then_Diagnostic()
	{
		var (diagnostics, compilation) = Run(Header + """

			public partial record MyForm(string Name, bool HasErrors);

			public partial class MyModel
			{
				public IState<MyForm> Form => State.Value(this, () => new MyForm("", false));
			}
			""");

		diagnostics.Should().ContainSingle(d => d.Id == "FEED1001")
			.Which.GetMessage().Should().Contain("HasErrors").And.Contain("MyForm");
		compilation.GetDiagnostics().Where(d => d.Severity == DiagnosticSeverity.Error).Should().BeEmpty();
	}

	[TestMethod]
	public void When_NoCollision_Then_NoDiagnostic()
	{
		var (diagnostics, compilation) = Run(Header + """

			public partial record MyForm(string Name);

			public partial class MyModel
			{
				public IState<MyForm> Form => State.Value(this, () => new MyForm(""));
			}
			""");

		diagnostics.Should().NotContain(d => d.Id == "FEED1001");
		compilation.GetDiagnostics().Where(d => d.Severity == DiagnosticSeverity.Error).Should().BeEmpty();
	}

	[TestMethod]
	public void When_UserViewModelDeclaresHasErrors_Then_NoConflict_And_Diagnostic()
	{
		// Note: The implicit pattern is restricted so the partial view model is not itself considered as a model.
		var (diagnostics, compilation) = Run(Header.Replace("namespace App;", "[assembly: Uno.Extensions.Reactive.Config.ImplicitBindables(\"MyModel$\")]" + Environment.NewLine + "namespace App;") + """

			public partial class MyModel
			{
				public IState<string> Name => State.Value(this, () => "");
			}

			public partial class MyViewModel
			{
				public bool HasErrors => true;
			}
			""");

		diagnostics.Should().ContainSingle(d => d.Id == "FEED1001")
			.Which.GetMessage().Should().Contain("HasErrors").And.Contain("MyViewModel");
		compilation.GetDiagnostics().Where(d => d.Severity == DiagnosticSeverity.Error || d.Id == "CS0108").Should().BeEmpty();
	}

	[TestMethod]
	[DataRow(1, "MyViewModel", "BindableMyViewModel")] // v1 generates a Bindable{Name} for each partial *ViewModel
	[DataRow(2, "MyModel", "BindableMyModel")]
	[DataRow(3, "MyModel", "MyViewModel")]
	public void When_NoCollision_Then_ViewModelExposesHasErrors(int toolVersion, string modelName, string viewModelName)
	{
		var (diagnostics, compilation) = Run(Header.Replace("BindableGenerationTool(3)", $"BindableGenerationTool({toolVersion})") + $$"""

			public partial class {{modelName}}
			{
				public IState<string> Name => State.Value(this, () => "");
			}
			""");

		diagnostics.Should().NotContain(d => d.Id == "FEED1001");
		GetGenerationErrors(compilation, toolVersion).Should().BeEmpty();
		var viewModel = compilation.GetSymbolsWithName(viewModelName, SymbolFilter.Type).OfType<INamedTypeSymbol>().Single();
		viewModel.GetMembers("HasErrors").Should().ContainSingle()
			.Which.Should().BeAssignableTo<IPropertySymbol>()
			.Which.DeclaredAccessibility.Should().Be(Accessibility.Public);
	}

	[TestMethod]
	[DataRow(1, "MyViewModel")]
	[DataRow(2, "MyModel")]
	[DataRow(3, "MyModel")]
	public void When_ModelDeclaresHasErrors_Then_DiagnosticForAllToolVersions(int toolVersion, string modelName)
	{
		var (diagnostics, compilation) = Run(Header.Replace("BindableGenerationTool(3)", $"BindableGenerationTool({toolVersion})") + $$"""

			public partial class {{modelName}}
			{
				public IState<string> Name => State.Value(this, () => "");

				public IFeed<bool> HasErrors => Feed.Async(async ct => false);
			}
			""");

		diagnostics.Should().ContainSingle(d => d.Id == "FEED1001");
		GetGenerationErrors(compilation, toolVersion).Should().BeEmpty();
	}

	// Note: The view models generated by the v1 of the tool do not compile against the current BindableViewModelBase (e.g. they do not implement
	//		 __Reactive_UpdateModel), no matter the validation: for that version we only ignore those errors which are not related to the validation.
	private static Diagnostic[] GetGenerationErrors(Compilation compilation, int toolVersion)
		=> compilation
			.GetDiagnostics()
			.Where(d => d.Severity == DiagnosticSeverity.Error)
			.Where(d => toolVersion is not 1 || d.GetMessage().Contains("HasErrors", StringComparison.Ordinal))
			.ToArray();

	private static (Diagnostic[] Diagnostics, Compilation Output) Run(string source)
	{
		var references = ((string)AppContext.GetData("TRUSTED_PLATFORM_ASSEMBLIES")!)
			.Split(Path.PathSeparator)
			.Where(path => Path.GetFileName(path) is { } name
				&& (name.StartsWith("System.", StringComparison.Ordinal)
					|| name.StartsWith("netstandard", StringComparison.Ordinal)
					|| name.StartsWith("Microsoft.Extensions.", StringComparison.Ordinal)
					|| (name.StartsWith("Uno.Extensions.", StringComparison.Ordinal) && !name.Contains("Generator", StringComparison.Ordinal))))
			.Select(path => MetadataReference.CreateFromFile(path));
		var compilation = CSharpCompilation.Create(
			"App",
			new[] { CSharpSyntaxTree.ParseText(source) },
			references,
			new CSharpCompilationOptions(OutputKind.DynamicallyLinkedLibrary, nullableContextOptions: NullableContextOptions.Enable));
		compilation.GetDiagnostics()
			.Where(diagnostic => diagnostic.Severity == DiagnosticSeverity.Error)
			.Should().BeEmpty("the fixture source must compile before the generator runs");

		CSharpGeneratorDriver
			.Create(new FeedsGenerator())
			.RunGeneratorsAndUpdateCompilation(compilation, out var output, out var diagnostics);

		return (diagnostics.ToArray(), output);
	}
}
